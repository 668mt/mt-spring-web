package mt.generator.mybatis.core.dialect;

import mt.generator.mybatis.core.model.ColumnDefinition;
import mt.generator.mybatis.core.model.ColumnType;
import mt.generator.mybatis.core.model.ForeignKeyDefinition;
import mt.generator.mybatis.core.model.IndexDefinition;
import mt.generator.mybatis.core.model.TableDefinition;
import mt.generator.mybatis.annotation.IndexType;
import org.junit.jupiter.api.Test;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * PostgreSQL 方言测试
 *
 * @author Martin
 */
class PostgreSqlDialectTest {

	private final PostgreSqlDialect dialect = new PostgreSqlDialect();

	/**
	 * 渲染简单类型
	 *
	 * @param columnType 列类型
	 * @return SQL 类型
	 */
	private String type(ColumnType columnType) {
		return dialect.renderColumnType(ColumnDefinition.builder()
				.javaType(Object.class).columnType(columnType).build());
	}

	@Test
	void supportsDriver() {
		assertTrue(dialect.supports("org.postgresql.Driver"));
		assertFalse(dialect.supports("com.mysql.cj.jdbc.Driver"));
		assertFalse(dialect.supports(null));
	}

	@Test
	void parseDatabaseName() {
		assertEquals("rec", dialect.getDatabaseName("jdbc:postgresql://127.0.0.1:5432/rec"));
		assertEquals("rec", dialect.getDatabaseName("jdbc:postgresql://127.0.0.1:5432/rec?ssl=true"));
	}

	@Test
	void maintenanceJdbcUrl() {
		assertEquals("jdbc:postgresql://127.0.0.1:5432/postgres",
				dialect.getMaintenanceJdbcUrl("jdbc:postgresql://127.0.0.1:5432/rec"));
		assertEquals("jdbc:postgresql://127.0.0.1:5432/postgres?ssl=true",
				dialect.getMaintenanceJdbcUrl("jdbc:postgresql://127.0.0.1:5432/rec?ssl=true"));
	}

	@Test
	void columnTypes() {
		assertEquals("integer", type(ColumnType.INTEGER));
		assertEquals("bigint", type(ColumnType.LONG));
		assertEquals("boolean", type(ColumnType.BOOLEAN));
		assertEquals("double precision", type(ColumnType.DOUBLE));
		assertEquals("real", type(ColumnType.FLOAT));
		assertEquals("timestamp", type(ColumnType.TIMESTAMP));
		assertEquals("date", type(ColumnType.DATE));
		assertEquals("bytea", type(ColumnType.BINARY));
		assertEquals("jsonb", type(ColumnType.JSON));
	}

	@Test
	void stringAndDecimalTypes() {
		assertEquals("varchar(255)", dialect.renderColumnType(ColumnDefinition.builder()
				.javaType(String.class).columnType(ColumnType.STRING).length(255).build()));
		assertEquals("numeric(10,2)", dialect.renderColumnType(ColumnDefinition.builder()
				.javaType(java.math.BigDecimal.class).columnType(ColumnType.DECIMAL).precision(10).scale(2).build()));
	}

	@Test
	void explicitColumnDefinitionIsNormalized() {
		assertEquals("text", dialect.renderColumnType(ColumnDefinition.builder()
				.javaType(String.class).columnType(ColumnType.STRING).columnDefinition("longtext").build()));
		assertEquals("bytea", dialect.renderColumnType(ColumnDefinition.builder()
				.javaType(byte[].class).columnType(ColumnType.BINARY).columnDefinition("blob").build()));
		assertEquals("timestamp", dialect.renderColumnType(ColumnDefinition.builder()
				.javaType(java.util.Date.class).columnType(ColumnType.TIMESTAMP).columnDefinition("datetime").build()));
	}

	/**
	 * 保留字要加引号，普通列名不加
	 * 驼峰列名不能加引号，否则和 MyBatis 生成的 SQL 大小写对不上
	 */
	@Test
	void identifierQuoting() {
		assertEquals("\"user\"", dialect.quoteIdentifier("user"));
		assertEquals("\"order\"", dialect.quoteIdentifier("order"));
		assertEquals("userId", dialect.quoteIdentifier("userId"));
		assertEquals("created_date", dialect.quoteIdentifier("created_date"));
	}

	@Test
	void identityClause() {
		ColumnDefinition column = ColumnDefinition.builder()
				.javaType(Long.class).columnType(ColumnType.LONG).autoIncrement(true).build();
		assertEquals("GENERATED BY DEFAULT AS IDENTITY", dialect.renderIdentityClause(column));
		column.setColumnType(ColumnType.STRING);
		assertNull(dialect.renderIdentityClause(column));
	}

	@Test
	void createTable() {
		TableDefinition table = TableDefinition.builder()
				.name("notice")
				.columns(Arrays.asList(
						ColumnDefinition.builder().name("id").javaType(Long.class).columnType(ColumnType.LONG)
								.autoIncrement(true).nullable(false).build(),
						ColumnDefinition.builder().name("title").javaType(String.class).columnType(ColumnType.STRING)
								.length(255).nullable(false).build(),
						ColumnDefinition.builder().name("userId").javaType(Long.class).columnType(ColumnType.LONG).build()))
				.primaryKeyColumns(Collections.singletonList("id"))
				.build();
		List<String> sqls = dialect.renderCreateTable(table);
		assertEquals(1, sqls.size());
		String sql = sqls.get(0);
		assertTrue(sql.startsWith("CREATE TABLE notice ("), sql);
		assertTrue(sql.contains("id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL"), sql);
		assertTrue(sql.contains("title varchar(255) NOT NULL"), sql);
		assertTrue(sql.contains("userId bigint"), sql);
		assertTrue(sql.contains("PRIMARY KEY (id)"), sql);
	}

	@Test
	void indexesAreCreatedByStandaloneStatements() {
		TableDefinition table = TableDefinition.builder()
				.name("notice")
				.columns(Collections.emptyList())
				.indexes(Arrays.asList(
						IndexDefinition.builder().name("idx_notice_user")
								.columns(Arrays.asList("userId", "status")).type(IndexType.normal).build(),
						IndexDefinition.builder().name(null)
								.columns(Collections.singletonList("noticeType")).type(IndexType.unique).build()))
				.build();
		List<String> sqls = dialect.renderIndexes(table);
		assertEquals(2, sqls.size());
		assertEquals("CREATE INDEX idx_notice_user ON notice (userId, status)", sqls.get(0));
		//索引名在库内唯一，所以要带表名
		assertEquals("CREATE UNIQUE INDEX INDEX_notice_noticeType ON notice (noticeType)", sqls.get(1));
	}

	@Test
	void fullTextIndexUsesGin() {
		TableDefinition table = TableDefinition.builder()
				.name("notice")
				.indexes(Collections.singletonList(IndexDefinition.builder()
						.name("idx_notice_content").columns(Collections.singletonList("content"))
						.type(IndexType.fulltext).build()))
				.build();
		List<String> sqls = dialect.renderIndexes(table);
		assertEquals("CREATE INDEX idx_notice_content ON notice USING GIN (to_tsvector('simple', coalesce(content, '')))",
				sqls.get(0));
	}

	@Test
	void hashIndex() {
		TableDefinition table = TableDefinition.builder()
				.name("notice")
				.indexes(Collections.singletonList(IndexDefinition.builder()
						.name("idx_notice_hash").columns(Collections.singletonList("userId"))
						.type(IndexType.hash).build()))
				.build();
		assertEquals("CREATE INDEX idx_notice_hash ON notice USING HASH (userId)",
				dialect.renderIndexes(table).get(0));
	}

	@Test
	void foreignKey() {
		ForeignKeyDefinition foreignKey = ForeignKeyDefinition.builder()
				.name("FK_notice_detail_notice_id_notice_id")
				.tableName("notice_detail")
				.columnName("notice_id")
				.referenceTableName("notice")
				.referencedColumnName("id")
				.cascadeType(mt.common.annotation.ForeignKey.CascadeType.DELETE)
				.build();
		assertEquals("ALTER TABLE notice_detail ADD CONSTRAINT FK_notice_detail_notice_id_notice_id "
						+ "FOREIGN KEY (notice_id) REFERENCES notice (id) ON DELETE CASCADE",
				dialect.renderForeignKey(foreignKey));
	}

	@Test
	void identifierLengthIsLimitedTo63() {
		TableDefinition table = TableDefinition.builder()
				.name("notice")
				.indexes(Collections.singletonList(IndexDefinition.builder()
						.name(null)
						.columns(Collections.singletonList("aVeryVeryVeryLongColumnNameThatIsLongerThan63Characters"))
						.type(IndexType.normal).build()))
				.build();
		String sql = dialect.renderIndexes(table).get(0);
		String indexName = sql.substring("CREATE INDEX ".length(), sql.indexOf(" ON "));
		assertEquals(63, indexName.length(), indexName);
	}
}
